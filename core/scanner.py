def scan_script_text(text: str) -> Dict[str, Any]:
    """
    对短视频文案进行全量违禁词排毒机审
    :param text: 输入待审文案字符串
    :return: 包含通过状态、违禁词列表、高危分类及建议的字典
    """
    if not text:
        return {"passed": True, "violations_count": 0, "violations": []}

    lines = text.splitlines()
    violations = []

    for line_idx, line in enumerate(lines, start=1):
        clean_line = line.strip()
        if not clean_line or clean_line.startswith("#"):
            continue

        for category, info in BANNED_RULES.items():
            matches = re.finditer(info["pattern"], clean_line, re.IGNORECASE)
            for m in matches:
                word = m.group()
                violations.append({
                    "line": line_idx,
                    "word": word,
                    "text_snippet": clean_line,
                    "category": category,
                    "reason": info["reason"],
                    "suggestion": info["suggestion"]
                })

    return {
        "passed": len(violations) == 0,
        "violations_count": len(violations),
        "violations": violations
    }
